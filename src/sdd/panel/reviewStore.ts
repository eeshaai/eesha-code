import * as fs from "fs";
import * as path from "path";

import { HISTORY_SUBDIR } from "../../core/loader/constants";
import { profilePath } from "../../core/loader/profilePaths";
import { workspaceFolderName } from "../../core/store/databaseLocation";
import { ReviewNote } from "../../view/templates/reviewNotes";

/**
 * Where a review's own artefacts live: the notes people left, and the
 * copies of a document that let the panel say what changed.
 *
 * Two stores because they have two different owners.
 *
 * `review.json` sits in the spec folder and is meant to be committed:
 * the next person to open the spec, on another machine or in a pull
 * request, has to see the notes. That is why a note's document path is
 * stored relative to the workspace root, with forward slashes - an
 * absolute path is the path on one laptop only. A document outside the
 * workspace has no useful relative form and stays absolute.
 *
 * The snapshot history is the opposite: it exists so the panel can show
 * what the last phase changed, it is regenerated by the next run, and
 * nobody wants every draft in their diff. So it is kept in the profile,
 * the same way the run database is - see `resolveDatabasePath` - and a
 * spec folder never picks up files the repository did not ask for.
 */

const NOTES_FILE = "review.json";

/** The shape written to disk. Versioned from the start, because this file outlives the code that wrote it. */
interface NotesFile {

    version: 1;

    notes: ReviewNote[];
}

export function notesPath(specFolder: string): string {

    return path.join(specFolder, NOTES_FILE);
}

/**
 * The stored form of a document path: relative to the workspace root,
 * forward slashes. Anything the root does not contain is handed back
 * untouched, because a ladder of `../..` is no more portable than the
 * absolute path.
 */
function relativeArtifact(root: string, artifact: string): string {

    if (!path.isAbsolute(artifact))
        return artifact;

    const relative = path.relative(root, artifact);

    return relative && !relative.startsWith("..") && !path.isAbsolute(relative)
        ? relative.split(path.sep).join("/")
        : artifact;
}

/**
 * The stored form read back as a path this machine can open.
 *
 * Absolute is left alone: it is a document outside the workspace.
 *
 * A relative path that resolves to nothing is tried once more against
 * the spec folder. It means the file was written under a different root
 * - `sdd.specsDir` moved, or the workspace folder is a level higher
 * up - and without this every note on the document would silently vanish.
 * The spec folder is the one anchor that travels with the notes.
 */
function absoluteArtifact(root: string, specFolder: string, artifact: string): string {

    if (path.isAbsolute(artifact))
        return artifact;

    const resolved = path.resolve(root, artifact);

    if (fs.existsSync(resolved))
        return resolved;

    const beside = path.join(specFolder, path.basename(artifact));

    return fs.existsSync(beside) ? beside : resolved;
}

/**
 * The notes on a spec.
 *
 * Unreadable is treated as empty rather than thrown. The file is
 * hand-editable and can arrive with a merge conflict in it; a panel
 * that refuses to open a spec over a malformed comment file has turned
 * a note into a blocker.
 */
export function readNotes(specFolder: string, root: string): ReviewNote[] {

    const file = notesPath(specFolder);

    if (!fs.existsSync(file))
        return [];

    try {

        const parsed = JSON.parse(fs.readFileSync(file, "utf8")) as NotesFile;

        return Array.isArray(parsed?.notes)
            ? parsed.notes.map(note => ({ ...note, artifact: absoluteArtifact(root, specFolder, note.artifact) }))
            : [];

    } catch {

        return [];
    }
}

export function writeNotes(specFolder: string, root: string, notes: ReviewNote[]): void {

    const file = notesPath(specFolder);

    // An empty set removes the file rather than leaving `{"notes":[]}`
    // in the repository. A spec nobody has commented on should look
    // like one.
    if (notes.length === 0) {

        if (fs.existsSync(file))
            fs.rmSync(file);

        return;
    }

    const body: NotesFile = {
        version: 1,
        notes: notes.map(note => ({ ...note, artifact: relativeArtifact(root, note.artifact) }))
    };

    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${JSON.stringify(body, undefined, 4)}\n`, "utf8");
}

/** `2026-09-02T17-30-00-000Z` - ISO order without the colons Windows refuses in a file name. */
function stamp(at: number): string {

    return new Date(at).toISOString().replace(/[:.]/g, "-");
}

/**
 * Where a spec folder's snapshots live: `~/.eesha/history/
 * <workspace>/<spec folder>/`. Both parts go through
 * {@link workspaceFolderName} - the same slug-plus-hash the run database
 * uses - so two spec folders that slug to the same text land apart.
 */
function historyDir(root: string, specFolder: string): string {

    return profilePath(HISTORY_SUBDIR, workspaceFolderName(root), workspaceFolderName(specFolder));
}

/**
 * Puts the document as it stands aside, so the next draft can be
 * compared against it.
 *
 * Called before a phase runs, never after: afterwards the old text is
 * gone. A document that does not exist writes no snapshot - an empty
 * baseline would mark the whole first draft as changed.
 */
export function snapshot(specFolder: string, root: string, artifact: string, at = Date.now()): void {

    if (!fs.existsSync(artifact))
        return;

    const directory = historyDir(root, specFolder);

    fs.mkdirSync(directory, { recursive: true });

    const name = path.basename(artifact);
    const extension = path.extname(name);
    const prefix = `${name.slice(0, name.length - extension.length)}.`;

    fs.copyFileSync(artifact, path.join(directory, `${prefix}${stamp(at)}${extension}`));

    /*
     * Everything older than the copy just taken, dropped.
     *
     * Only the newest is ever read - see `baseline` - so the rest are
     * dead weight, and nothing else sweeps this folder. Pruning here
     * rather than on a timer is what makes "the last run" true: the
     * rule holds because taking a new copy is the only way to make an
     * old one stale.
     *
     * A failure is swallowed. A file another program is holding open
     * must not fail the phase that was about to run.
     */
    for (const entry of olderThan(directory, prefix, extension, `${prefix}${stamp(at)}${extension}`))
        try {
            fs.unlinkSync(path.join(directory, entry));
        } catch {
            // Left behind. The next snapshot tries again.
        }
}

/** This document's snapshots, newest first, skipping the one just written. */
function olderThan(directory: string, prefix: string, extension: string, keep: string): string[] {

    return snapshots(directory, prefix, extension).filter(entry => entry !== keep);
}

/** Every snapshot of one document in a folder, oldest first - the stamp is ISO, so name order is time order. */
function snapshots(directory: string, prefix: string, extension: string): string[] {

    if (!fs.existsSync(directory))
        return [];

    return fs.readdirSync(directory)
        .filter(entry => entry.startsWith(prefix) && entry.endsWith(extension))
        .sort();
}

/**
 * Throws away every document this workspace has put aside.
 *
 * Also for a spec folder that has since been deleted - its directory
 * is keyed by the folder's name, so nothing else will ever
 * reach it again. Returns how many files went, so the caller can say.
 */
export function clearHistory(root: string): number {

    const directory = profilePath(HISTORY_SUBDIR, workspaceFolderName(root));

    if (!fs.existsSync(directory))
        return 0;

    let removed = 0;

    for (const spec of fs.readdirSync(directory, { withFileTypes: true })) {

        if (!spec.isDirectory())
            continue;

        const inside = path.join(directory, spec.name);

        for (const entry of fs.readdirSync(inside)) {

            fs.rmSync(path.join(inside, entry), { force: true });
            removed++;
        }

        fs.rmdirSync(inside);
    }

    return removed;
}

/**
 * The most recent snapshot of a document, or undefined when none was
 * ever taken. Undefined is not the same as an empty document: "nothing
 * to compare" shows no marks, where "it used to be empty" would show
 * every line as new.
 */
export function baseline(specFolder: string, root: string, artifact: string): string | undefined {

    const directory = historyDir(root, specFolder);

    const name = path.basename(artifact);
    const extension = path.extname(name);
    const prefix = `${name.slice(0, name.length - extension.length)}.`;

    // The stamp is ISO, so lexical order is chronological order and the
    // last name is the newest file. No stat call, and no tie to a file
    // system's idea of modification time.
    const newest = snapshots(directory, prefix, extension).pop();

    return newest === undefined
        ? undefined
        : fs.readFileSync(path.join(directory, newest), "utf8");
}
